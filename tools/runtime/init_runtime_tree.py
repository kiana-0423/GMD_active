#!/usr/bin/env python
# Ported from PHAL (runtime/** skeleton, configs/runtime.yaml) at 96263b6; MIT License, see NOTICE.
"""Create the runtime data tree and render the runtime config overlay for a given root.

    python tools/runtime/init_runtime_tree.py --root /scratch/me/gmd_runtime        # create the tree
    python tools/runtime/init_runtime_tree.py --root /runtime --overlay containers/config/runtime.yaml
    python tools/runtime/init_runtime_tree.py --root /scratch/me/gmd_runtime --check

PHAL tracked an empty ``runtime/`` skeleton in git and hard-coded ``/runtime`` in
``configs/runtime.yaml``. Here the root is an argument; the tree and the overlay are generated from
the same table, so the documented contract (docs/runtime-data-contract.md) and the config paths
cannot drift apart. The overlay is merged over a run configuration with
``gmd_active_learning.utils.yaml.merge_yaml_files``; ``gmd-al run --work-dir <root>/runs/<run_id>``
puts each persistent run (workflow.sqlite, registry, datasets, events) under ``runs/``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path, PurePosixPath
from typing import Any, Sequence

import yaml

# Relative directory -> purpose. ``md/`` holds GMD outputs and ``models/`` GMD_SGT models (PHAL:
# LAMMPS dumps and Allegro models); ``cp2k_ml/`` is for ML-SCF models only.
RUNTIME_TREE: dict[str, str] = {
    "runs": "one gmd-al --work-dir per run: workflow.sqlite, models/ registry, datasets/ store, events, segments",
    "models/latest": "GMD_SGT checkpoints and TorchScript exports handed to gmd-al init",
    "models/archive": "retired GMD_SGT models kept for provenance",
    "datasets": "imported or seed training data (legacy PHAL/LAMMPS imports land here)",
    "checkpoints": "GMD_SGT training checkpoints outside a run",
    "md/runs": "stand-alone GMD runs (input xyz, run.in, frames.extxyz, output.log)",
    "md/restart": "GMD checkpoint files (checkpoint v3) for restarts",
    "cp2k/tasks": "labeling task directories (cp2k.task_dir): task.json, attempts/, result.json",
    "cp2k/outputs": "CP2K outputs collected outside the labeling service",
    "cp2k/scf": "SCF recordings (scf.recording.output_dir)",
    "cp2k/scf_dataset/train": "curated ML-SCF dataset, train split (scf.dataset.root)",
    "cp2k/scf_dataset/validation": "curated ML-SCF dataset, validation split",
    "cp2k/scf_dataset/test": "curated ML-SCF dataset, test split",
    "cp2k_ml/models": "ML-SCF density models only (never interatomic potentials)",
    "cp2k_ml/checkpoints": "ML-SCF training checkpoints",
    "cp2k_ml/validation": "ML-SCF validation evidence",
    "cp2k_ml/predictions": "ML-SCF predicted densities (scf.ml_scf.prediction_dir)",
    "cp2k_ml/logs": "ML-SCF logs",
    "cp2k_ml/cache": "ML-SCF caches",
    "logs": "job and probe logs (PBS summaries under logs/<probe>/)",
    "cache": "disposable caches",
}


def overlay(root: str | Path) -> dict[str, Any]:
    """The runtime config overlay: every runtime path of the run configuration under ``root``."""

    base = PurePosixPath(str(root)) if str(root).startswith("/") else Path(root).resolve()
    return {
        "cp2k": {"task_dir": str(base / "cp2k" / "tasks")},
        "scf": {
            # Observational only (as in PHAL's container overlay): recordings never change a label.
            "recording": {"enabled": True, "output_dir": str(base / "cp2k" / "scf")},
            "dataset": {"root": str(base / "cp2k" / "scf_dataset")},
        },
    }


def overlay_text(root: str | Path) -> str:
    header = (
        "# Runtime overlay: GENERATED by tools/runtime/init_runtime_tree.py --root "
        f"{root} --overlay <this file>; do not edit by hand.\n"
        "# Merge over a run configuration (later files win):\n"
        "#   merge_yaml_files(\"my_run.yaml\", \"containers/config/runtime.yaml\")\n"
        f"# and run with --work-dir {PurePosixPath(str(root)) / 'runs' / '<run_id>'}. Contract: docs/runtime-data-contract.md\n"
    )
    return header + yaml.safe_dump(overlay(root), sort_keys=False, default_flow_style=False)


def create_tree(root: Path) -> list[Path]:
    created = []
    for relative in RUNTIME_TREE:
        path = root / relative
        if not path.is_dir():
            path.mkdir(parents=True, exist_ok=True)
            created.append(path)
    readme = root / "README.md"
    if not readme.exists():
        lines = ["# GMD_active runtime data root", "", "Generated by tools/runtime/init_runtime_tree.py. Nothing here is source;",
                 "see docs/runtime-data-contract.md.", ""]
        lines += [f"- `{relative}/`: {purpose}" for relative, purpose in RUNTIME_TREE.items()]
        readme.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return created


def missing(root: Path) -> list[str]:
    return [relative for relative in RUNTIME_TREE if not (root / relative).is_dir()]


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", required=True, help="runtime root (e.g. /runtime inside containers)")
    parser.add_argument("--overlay", type=Path, default=None, help="write the runtime config overlay for --root here")
    parser.add_argument("--check", action="store_true", help="only verify that the tree exists")
    parser.add_argument("--no-create", action="store_true", help="do not create directories (e.g. when only rendering the overlay)")
    args = parser.parse_args(argv)
    root = Path(args.root)
    if args.check:
        absent = missing(root)
        print(json.dumps({"root": str(root), "missing": absent}))
        return 1 if absent else 0
    report: dict[str, Any] = {"root": str(root)}
    if not args.no_create:
        report["created"] = [str(path) for path in create_tree(root)]
    if args.overlay is not None:
        args.overlay.parent.mkdir(parents=True, exist_ok=True)
        args.overlay.write_text(overlay_text(args.root), encoding="utf-8")
        report["overlay"] = str(args.overlay)
    print(json.dumps(report))
    return 0


if __name__ == "__main__":
    sys.exit(main())
