"""Render docs/migration/feature_ledger.yaml as a Markdown overview.

The YAML file is the source of truth; the Markdown file is generated and should
not be edited by hand.

Usage (from the GMD_active repository root)::

    python tools/migration/render_ledger.py
"""

from __future__ import annotations

import argparse
from collections import Counter
from pathlib import Path
from typing import Any

import yaml

AREA_ORDER: tuple[str, ...] = (
    "monitoring", "events", "hotspots", "extraction", "candidates", "datasets", "training",
    "labeling", "scheduling", "backends", "md", "config", "cli", "io", "utils", "scf",
    "tooling", "containers", "docs", "tests",
)


def _cell(value: Any, limit: int | None = None) -> str:
    if isinstance(value, list):
        value = ", ".join(str(item) for item in value)
    text = " ".join(str(value).split())
    if limit is not None and len(text) > limit:
        text = text[: limit - 1].rstrip() + "…"
    return text.replace("|", "\\|")


def _counter_table(title: str, counts: Counter[str]) -> list[str]:
    lines = [f"| {title} | Entries |", "|---|---:|"]
    lines += [f"| {key} | {counts[key]} |" for key in sorted(counts, key=str)]
    return lines


def render(ledger: list[dict[str, Any]]) -> str:
    by_area: dict[str, list[dict[str, Any]]] = {}
    for entry in ledger:
        by_area.setdefault(entry["area"], []).append(entry)

    lines: list[str] = [
        "# PHAL → GMD_active feature ledger",
        "",
        "<!-- Generated by tools/migration/render_ledger.py from feature_ledger.yaml. Do not edit. -->",
        "",
        f"{len(ledger)} entries. The YAML ledger is the source of truth; "
        "`python tools/migration/check_ledger.py` validates it against `phal_inventory.json`.",
        "",
        "## Summary",
        "",
    ]
    lines += _counter_table("Migration status", Counter(e["migration_status"] for e in ledger)) + [""]
    lines += _counter_table("PHAL status", Counter(e["phal_status"] for e in ledger)) + [""]
    lines += _counter_table("Disposition", Counter(e["disposition"] for e in ledger)) + [""]
    lines += _counter_table("Phase", Counter(f"Phase {e['phase']}" for e in ledger)) + [""]

    ordered = [area for area in AREA_ORDER if area in by_area] + sorted(set(by_area) - set(AREA_ORDER))
    for area in ordered:
        lines += [
            f"## {area.capitalize()}",
            "",
            "| ID | Feature | PHAL status | Destination | Disposition | Phase | Status |",
            "|---|---|---|---|---|---:|---|",
        ]
        for entry in sorted(by_area[area], key=lambda item: item["id"]):
            lines.append(
                f"| {entry['id']} | {_cell(entry['feature'], 70)} | {entry['phal_status']} | "
                f"`{_cell(entry['destination'], 80)}` | {entry['disposition']} | {entry['phase']} | "
                f"{entry['migration_status']} |"
            )
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Render the feature ledger as Markdown.")
    parser.add_argument("--ledger", type=Path, default=Path("docs/migration/feature_ledger.yaml"))
    parser.add_argument("--out", type=Path, default=Path("docs/migration/feature_ledger.md"))
    args = parser.parse_args(argv)
    ledger = yaml.safe_load(args.ledger.read_text(encoding="utf-8"))
    args.out.write_text(render(ledger), encoding="utf-8")
    print(f"wrote {args.out} ({len(ledger)} entries)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
